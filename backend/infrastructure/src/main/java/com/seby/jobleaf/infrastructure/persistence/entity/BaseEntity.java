package com.seby.jobleaf.infrastructure.persistence.entity;

import jakarta.persistence.Column;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PrePersist;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.envers.Audited;
import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedBy;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.domain.Persistable;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.time.Instant;
import java.util.UUID;

/**
 * JPA abstract class used for auditing.
 * <p>
 * {@link Audited} is required so Envers also writes the inherited audit columns into the {@code _aud} tables.
 * <p>
 * Ids are generated by the application, so Spring Data cannot tell new entities from existing ones by a null id.
 * {@link Persistable#isNew()} uses {@code createdAt} instead: it is only empty before the first insert, which lets
 * {@code save()} call {@code persist} (one INSERT) instead of {@code merge} (SELECT + INSERT).
 */
@Getter
@MappedSuperclass
@Audited
@EntityListeners(AuditingEntityListener.class)
public abstract class BaseEntity implements Persistable<UUID> {

    @Setter
    @Id
    @Column(name = "id", nullable = false, updatable = false)
    protected UUID id;

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    protected Instant createdAt;

    @CreatedBy
    @Column(name = "created_by", updatable = false)
    protected UUID createdBy;

    @LastModifiedDate
    @Column(name = "updated_at")
    protected Instant updatedAt;

    @LastModifiedBy
    @Column(name = "updated_by")
    protected UUID updatedBy;

    /**
     * {@inheritDoc}
     */
    @Override
    public boolean isNew() {
        return createdAt == null;
    }

    /**
     * Copies the audit values of an already persisted record onto this entity.
     * Keeping {@code createdAt} makes {@link #isNew()} return {@code false}.
     * <p>
     * Do not use it to set audit values for new records: those come from the auditing listener.
     */
    public void restoreAuditFields(Instant createdAt, UUID createdBy, Instant updatedAt, UUID updatedBy) {
        this.createdAt = createdAt;
        this.createdBy = createdBy;
        this.updatedAt = updatedAt;
        this.updatedBy = updatedBy;
    }

    @PrePersist
    protected void onCreate() {
        if (id == null) {
            id = UUID.randomUUID();
        }
    }
}
